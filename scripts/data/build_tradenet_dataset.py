"""
scripts/data/build_tradenet_dataset.py
────────────────────────────────────────────────────────────────────────────────
Convert *_fusion.jsonl trade logs → data/training.json for train_pipeline.py tradenet.

Source logs are generated by backtest_v2.py (--scorer calibrated|static) or the
live engine hook.  Each JSONL file contains paired ENTRY+EXIT records linked by
trade_id.  This script pairs them via validate_logs(), then emits the binary-label
format expected by run_training_pipeline().

Usage:
  python scripts/data/build_tradenet_dataset.py logs/EURUSD_fusion.jsonl
  python scripts/data/build_tradenet_dataset.py logs/EURUSD_fusion.jsonl logs/GBPUSD_fusion.jsonl
  python scripts/data/build_tradenet_dataset.py logs/EURUSD_fusion.jsonl --output data/my_training.json

Output schema (list of records):
  [{"features": {"open": 1.2345, ...35 keys...}, "label": 0|1}, ...]

Then train:
  python scripts/training/train_pipeline.py tradenet \\
      --data data/training.json --output results/tradenet_result.json
────────────────────────────────────────────────────────────────────────────────
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_SRC = Path(__file__).resolve().parents[2] / "src"
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from features.dataset_validator import validate_logs, MIN_RECORDS_TO_TRAIN


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Convert *_fusion.jsonl logs → data/training.json for TradeNet"
    )
    ap.add_argument("logs", nargs="+", help="One or more *_fusion.jsonl paths")
    ap.add_argument("--output", default="data/training.json",
                    help="Output JSON path (default: data/training.json)")
    args = ap.parse_args()

    records, report = validate_logs(*args.logs)

    if not report.is_trainable:
        print(
            f"ERROR: only {report.valid_for_training} valid records "
            f"(minimum {MIN_RECORDS_TO_TRAIN} required). Aborting."
        )
        sys.exit(1)

    training = [
        {"features": r["features"], "label": int(r["outcome"]["win"])}
        for r in records
    ]

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(training, f, indent=2)

    n_win  = sum(1 for r in training if r["label"] == 1)
    n_loss = len(training) - n_win
    print(f"Wrote {len(training)} records → {out}  (win={n_win}, loss={n_loss})")


if __name__ == "__main__":
    main()
