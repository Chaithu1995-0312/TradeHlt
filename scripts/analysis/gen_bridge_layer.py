def measure_dtypes() -> dict:
    """Measure the REAL dtypes by running FeaturePipeline.run() on a data slice.

    Returns {} when the corpus is unavailable (the HTML then says 'not measured' rather than
    inventing a dtype). This is a measurement, not a declaration.
    """
    src = REPO_ROOT / "data" / "mt5" / "XAUUSD_M15.csv"
    if not src.exists():
        return {}
    try:
        import logging
        import warnings
        import pandas as pd
        logging.disable(logging.CRITICAL)
        warnings.filterwarnings("ignore")
        from features.feature_pipeline import FeaturePipeline
        from data_ingestion.corpus_store import load as _corpus_load  # CH-corpus-ssot: the corpus SSOT
        df = _corpus_load(src).frame(nrows=400)
        pipe = FeaturePipeline(df)
        enriched, vectors = pipe.run()
        logging.disable(logging.NOTSET)
        return {
            "source": "data/mt5/XAUUSD_M15.csv (first 400 rows)",
            "enriched": {k: str(t) for k, t in enriched.dtypes.items()},
            "vector_dtype": str(vectors.dtype),
            "shape": [int(vectors.shape[0]), int(vectors.shape[1])],
        }
    except Exception as exc:  # noqa: BLE001 — a measurement failure must not break generation
        return {"error": f"{type(exc).__name__}: {exc}"}


