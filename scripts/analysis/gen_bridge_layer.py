#!/usr/bin/env python
"""gen_bridge_layer.py — generate the Bridge Layer specification artifacts.

WHAT THIS IS
------------
A BRIDGE, not a trading-education layer. It maps trading VOCABULARY onto the repository's
existing measurement authorities, end to end:

    OHLCV -> Feature Ontology -> State Ontology -> Decision Ontology -> Measurement Ontology

Every fact in the emitted artifacts is READ FROM THE LIVE AUTHORITIES at generation time
(feature_schema, the ontology YAML, the CRT state identity YAML). Nothing is transcribed by
hand, so the bridge cannot drift from the code it describes.

SOURCE AUTHORITIES (never modified by this script)
--------------------------------------------------
  src/features/feature_schema.py              CANONICAL_FEATURES, _FM_ID_TO_NAME, hashes
  src/features/feature_states.py              FeatureStateEncoder (state ontology)
  configs/formulas/market_ontology.yaml       sections, categories, impl, states
  configs/formulas/crt_state_identity.yaml    CRT state identities
  configs/formulas/market_crt_states.yaml     resolver predicates

OUTPUTS
-------
  bridge_layer/README.md
  bridge_layer/CANONICAL_FEATURES.html
  bridge_layer/concepts.yaml
  bridge_layer/feature_schema.bridge.md
  bridge_layer/state_ontology.md
  bridge_layer/crt_engine_v2_concept_map.md
  bridge_layer/crt_state_resolver_bridge.md

USAGE
-----
    python scripts/analysis/gen_bridge_layer.py            # write
    python scripts/analysis/gen_bridge_layer.py --check    # validate only, no writes

Generated files must not be hand-edited.
"""
