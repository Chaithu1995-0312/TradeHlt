REQUIRED_CONCEPT_FIELDS = (
    "id", "concept", "observable_definition", "feature_representation",
    "state_representation", "authority_module", "storage_representation",
    "evidence_artifact", "observability", "status",
)
VALID_STATUS = {
    "present", "present_unwired", "present_no_resolver_predicate",
    "present_constructor_unreachable", "present_undefined", "absent",
}
VALID_OBSERVABILITY = {"directly_observable", "derived"}


def validate(schema: dict, ont: dict, concepts: list, resolver_states: list) -> list:
    """Return a list of problem strings. Empty list == bridge is internally consistent.

    Distinguishes VECTOR-BOUND FM ids (`fm_ids`, must be in `_FM_ID_TO_NAME`) from DECLARED
    NON-VECTOR FM ids (`non_vector_fm_ids`, must exist in the ontology but must NOT be
    vector-bound). Conflating the two was the first real defect this gate caught.
    """
    problems: list[str] = []

    feats = schema["features"]
    if len(feats) != schema["dim"]:
        problems.append(f"CANONICAL_FEATURES has {len(feats)} entries, dim says {schema['dim']}")
    if len(set(feats)) != len(feats):
        problems.append(f"duplicate canonical feature names: {sorted(set(feats))}")

    fm_vals = list(schema["fm_to_name"].values())
    if set(fm_vals) != set(feats):
        problems.append(
            "FM-ID map is not bijective with CANONICAL_FEATURES: "
            f"{sorted(set(feats) ^ set(fm_vals))}"
        )
    if len(fm_vals) != len(set(fm_vals)):
        problems.append("two FM ids bound to the same canonical feature name")

    seen_ids: set = set()
    for c in concepts:
        cid = c.get("id", "<no id>")
        if cid in seen_ids:
            problems.append(f"{cid}: duplicate concept id")
        seen_ids.add(cid)
        for f in REQUIRED_CONCEPT_FIELDS:
            if not c.get(f):
                problems.append(f"{cid} ({c.get('concept')}): missing/empty field {f!r}")
        if c.get("status") not in VALID_STATUS:
            problems.append(f"{cid}: unknown status {c.get('status')!r}")
        if c.get("observability") not in VALID_OBSERVABILITY:
            problems.append(f"{cid}: unknown observability {c.get('observability')!r}")
        if c.get("status") == "absent" and c.get("authority_module"):
            problems.append(f"{cid}: status absent but authority_module is set")
        if str(c.get("status", "")).startswith("present") and not c.get("authority_module"):
            problems.append(f"{cid}: status present but authority_module is empty")

    known_fm = set(schema["fm_to_name"])
    for c in concepts:
        for fm in c.get("fm_ids", []):
            if fm not in known_fm:
                problems.append(
                    f"{c.get('id')}: cites vector-bound FM id {fm!r} which is NOT in "
                    f"_FM_ID_TO_NAME (declared non-vector identities belong in "
                    f"non_vector_fm_ids)"
                )

    # declared-but-non-vector identities: must exist in the ontology, must NOT be vector-bound
    ont_fm_all = {e["fm_id"] for e in ont["entries"].values() if e.get("fm_id")}
    for c in concepts:
        for fm in c.get("non_vector_fm_ids", []):
            if fm in known_fm:
                problems.append(
                    f"{c.get('id')}: lists {fm!r} as non-vector but it IS vector-bound"
                )
            elif fm not in ont_fm_all:
                problems.append(
                    f"{c.get('id')}: non_vector_fm_ids cites {fm!r} which no ontology "
                    f"entry declares"
                )

    for c in concepts:
        if c.get("status") == "present_no_resolver_predicate" and c.get("concept") in resolver_states:
            problems.append(
                f"{c.get('id')}: declared present_no_resolver_predicate but "
                f"{c.get('concept')!r} IS a resolver state"
            )
    return problems


def coverage_report(schema: dict) -> dict:
    """Which canonical features the bridge names, and which it does not."""
    named = set()
    for c in CONCEPTS:
        for fm in c.get("fm_ids", []):
            nm = schema["fm_to_name"].get(fm)
            if nm:
                named.add(nm)
    return {
        "canonical_total": len(schema["features"]),
        "named_count": len(named),
        "named_by_a_concept": sorted(named),
        "not_named": sorted(set(schema["features"]) - named),
    }


