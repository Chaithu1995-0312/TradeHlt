def render_resolver_bridge(crt: dict, resolver_states: list) -> str:
    """Constructor matrix: which states each constructor can actually reach, and why not."""
    st = crt["states"]
    cons = crt["constructors"]
    lines = [
        "# crt_state_resolver_bridge.md",
        "",
        "> **GENERATED — do not edit by hand.** Regenerate with "
        "`python scripts/analysis/gen_bridge_layer.py`.",
        "",
        "CRT state identity is constructor-NEUTRAL: `crt_state_identity.yaml` declares what a "
        "state IS; the engine (`crt_engine_v2.py`) and the resolver (`crt_state_resolver.py`) are "
        "two CONSTRUCTORS of that one identity. A future constructor registers under "
        "`constructors:`, never re-declares `states:`. This file is the reachability bridge "
        "between vocabulary and each constructor.",
        "",
        f"Identity schema `{crt.get('schema')}` v`{crt.get('version')}`. "
        f"{len(st)} states, {len(cons)} declared constructors.",
        "",
        "## Constructor capability contract",
        "",
        "| Constructor | runtime_eligible | reaches_signal_state | produces_trade_geometry "
        "| produces_occupancy | produces_memory | covers_states |",
        "|---|:--:|:--:|:--:|:--:|:--:|---|",
    ]
    for cname, c in cons.items():
        cap = c["capabilities"]
        lines.append(
            f"| `{cname}` | {cap.get('runtime_eligible')} "
            f"| {cap.get('reaches_signal_state')} | {cap.get('produces_trade_geometry')} "
            f"| {cap.get('produces_occupancy')} | {cap.get('produces_memory')} "
            f"| {len(cap.get('covers_states') or [])} of {len(st)} |"
        )
    lines += ["", "### Blocking gaps", ""]
    any_gap = False
    for cname, c in cons.items():
        for g in (c["capabilities"].get("blocking_gaps") or []):
            any_gap = True
            lines.append(
                f"- **`{cname}` ({g.get('id') or 'UNNAMED'})** — capability "
                f"`{g.get('capability')}`: {g.get('summary')}"
            )
    if not any_gap:
        lines.append("- none declared")
    lines += [
        "",
        "## Per-state coverage by constructor",
        "",
        "`not covered` means the constructor's capability contract does not list the state in "
        "`covers_states` — it makes no claim about it at all.",
        "",
    ]
    hdr = "| State | ID | " + " | ".join(f"`{c}`" for c in cons) + " |"
    lines += [hdr, "|---|---|" + "|".join(["---"] * len(cons)) + "|"]
    for name, s in st.items():
        cells = []
        for c in cons:
            covered = name in (cons[c]["capabilities"].get("covers_states") or [])
            cs = cons[c]["state_status"].get(name) or {}
            if not covered:
                cells.append("not covered")
            elif cs.get("defined") is False:
                cells.append("**undefined**")
            elif cs.get("reachable") is False:
                cells.append("**unreachable**")
            elif cs.get("reachable") is True:
                cells.append("reachable")
            else:
                cells.append("covered")
        lines.append(f"| `{name}` | `{s['id']}` | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Named gaps (the honest part of the bridge)",
        "",
    ]
    for name, s in st.items():
        for c in cons:
            cs = cons[c]["state_status"].get(name)
            if cs and cs.get("unreachable_reason"):
                lines.append(f"- **`{name}` / `{c}`** — {cs['unreachable_reason']}")
            if cs and cs.get("construction_diverges_from_engine"):
                lines.append(
                    f"- **`{name}` / `{c}`** — `construction_diverges_from_engine: true` "
                    "(declared divergence, not disputed)"
                )
    missing = [n for n in st if n not in resolver_states]
    if missing:
        lines += [
            "",
            "## States with no resolver predicate",
            "",
            "Declared in the identity authority, but `configs/formulas/market_crt_states.yaml` "
            "carries **no `when:` block** for them, so the resolver constructor cannot resolve "
            "them. The engine constructor is unaffected.",
            "",
        ]
        for n in missing:
            lines.append(f"- `{n}` ({st[n]['id']}) — subgraph `{st[n]['subgraph']}`")
        lines.append("")
    lines += [
        "",
        "## Reading rule",
        "",
        "`reachable` here means *this constructor's config declares and can reach the state*, "
        "NOT that a live trade path exists. Runtime eligibility is the separate "
        "`capabilities.runtime_eligible` flag, and promotion is a governance act (M4 "
        "QualificationGate -> PromotionManager) — never implied by a reachability cell.",
        "",
    ]
    return "\n".join(lines) + "\n"


