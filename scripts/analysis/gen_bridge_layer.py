def render_feature_schema_bridge(schema: dict, ont: dict, cov: dict) -> str:
    """FM-ID <-> concept <-> vector index <-> authority mapping."""
    entries = ont["entries"]
    by_fm = {}
    for c in CONCEPTS:
        for fm in c.get("fm_ids", []):
            by_fm.setdefault(fm, []).append(c["concept"])
    lines = [
        "# feature_schema.bridge.md",
        "",
        "> **GENERATED — do not edit by hand.** Regenerate with "
        "`python scripts/analysis/gen_bridge_layer.py`.",
        "",
        "The FM-ID ↔ concept ↔ vector-index ↔ authority bridge. Every row is read from "
        "`src/features/feature_schema.py` and `configs/formulas/market_ontology.yaml` at "
        "generation time.",
        "",
        f"Schema dimension **{schema['dim']}** · `SCHEMA_HASH` `{schema['schema_hash']}` · "
        f"`FEATURE_ORDER_HASH` `{schema['order_hash']}`",
        "",
        "## Vector index ↔ identity ↔ concept",
        "",
        "| Idx | Canonical name | FM-ID | Ontology section | Category | Concept(s) |",
        "|---:|---|---|---|---|---|",
    ]
    for i, name in enumerate(schema["features"]):
        meta = entries.get(name, {})
        fm = schema["name_to_fm"].get(name, "")
        concepts = ", ".join(by_fm.get(fm, [])) or "—"
        lines.append(
            f"| {i} | `{name}` | `{fm}` | {meta.get('section', '—')} | "
            f"{meta.get('category', '—')} | {concepts} |"
        )
    # Declared-but-NON-vector identities that a concept still needs to name. These occupy no
    # canonical slot, so they cannot appear in the vector table above; omitting them would hide
    # real measured quantities from the bridge.
    fm_by_name = {e["fm_id"]: n for n, e in entries.items() if e.get("fm_id")}
    nv_rows = []
    for c in CONCEPTS:
        for fm in c.get("non_vector_fm_ids", []):
            nv_rows.append(
                f"| `{fm}` | `{fm_by_name.get(fm, '—')}` | "
                f"{entries.get(fm_by_name.get(fm), {}).get('section', '—')} | "
                f"{entries.get(fm_by_name.get(fm), {}).get('category', '—')} | {c['concept']} |"
            )
    if nv_rows:
        lines += [
            "",
            "## Declared but NOT vector-bound (no canonical slot)",
            "",
            "These identities are real, measured, and governed — but `lineage.vector_key` is "
            "empty, so they are NOT part of the 48-dim vector. A bridge that listed only vector "
            "rows would silently drop them.",
            "",
            "| FM-ID | Ontology name | Section | Category | Concept |",
            "|---|---|---|---|---|",
        ]
        lines += nv_rows
    lines += [
        "",
        "## Coverage",
        "",
        f"- Canonical features: **{cov['canonical_total']}**",
        f"- Named by at least one concept: **{cov['named_count']}**",
        f"- Not named by any concept: {len(cov['not_named'])}",
        "",
    ]
    if cov["not_named"]:
        lines.append("Features with no concept mapping (measured, not yet bridged to vocabulary):")
        lines.append("")
        for n in cov["not_named"]:
            fm = schema["name_to_fm"].get(n, "")
            lines.append(f"- `{n}` ({fm}) — {entries.get(n, {}).get('section', '—')}")
        lines.append("")
    return "\n".join(lines) + "\n"


