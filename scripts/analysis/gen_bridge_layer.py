# ----------------------------------- main -------------------------------------

def main(argv: list | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the Bridge Layer specification.")
    ap.add_argument("--check", action="store_true",
                    help="validate only; write nothing (exit 1 on any problem)")
    ap.add_argument("--no-measure", action="store_true",
                    help="skip the FeaturePipeline dtype measurement (faster)")
    args = ap.parse_args(argv)

    schema = read_schema()
    ont = read_ontology()
    states = read_states()
    crt = read_crt_identity()
    resolver_states = read_resolver_states()
    git = git_facts()

    problems = validate(schema, ont, CONCEPTS, resolver_states)
    if problems:
        print("BRIDGE LAYER VALIDATION FAILED — nothing written:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1

    cov = coverage_report(schema)
    dt = {} if args.no_measure else measure_dtypes()

    print(f"bridge layer: {len(CONCEPTS)} concepts, {schema['dim']} canonical features, "
          f"{len(crt['states'])} CRT states, {len(crt['constructors'])} constructors")
    print(f"  coverage: {cov['named_count']}/{cov['canonical_total']} features named by a concept")
    print(f"  dtypes: {dt.get('source') or dt.get('error') or 'not measured'}")
    print(f"  commit: {git['commit'][:12]} on {git['branch']}")

    if args.check:
        print("validation OK (--check: no files written)")
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    artifacts = {
        "README.md": render_readme(schema, crt, states, cov, git, dt),
        "CANONICAL_FEATURES.html": render_html(schema, ont, dt),
        "concepts.yaml": render_concepts_yaml(schema, cov, git),
        "feature_schema.bridge.md": render_feature_schema_bridge(schema, ont, cov),
        "state_ontology.md": render_state_ontology(states),
        "crt_engine_v2_concept_map.md": render_crt_concept_map(crt, resolver_states),
        "crt_state_resolver_bridge.md": render_resolver_bridge(crt, resolver_states),
    }
    for name, body in artifacts.items():
        (OUT / name).write_text(body, encoding="utf-8")
        written.append((name, len(body)))

    for name, n in written:
        print(f"  wrote bridge_layer/{name} ({n} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())



