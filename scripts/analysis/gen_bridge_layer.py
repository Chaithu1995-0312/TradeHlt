# ----------------------------- authority readers -----------------------------

def _load_yaml(path: Path) -> dict:
    import yaml
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def read_schema() -> dict:
    """Live feature schema facts — the Measurement Ontology anchor."""
    from features.feature_schema import (
        CANONICAL_FEATURES, CANONICAL_FEATURE_DIM, _FM_ID_TO_NAME,
        SCHEMA_HASH, FEATURE_ORDER_HASH,
    )
    return {
        "dim": int(CANONICAL_FEATURE_DIM),
        "features": list(CANONICAL_FEATURES),
        "fm_to_name": dict(_FM_ID_TO_NAME),
        "name_to_fm": {v: k for k, v in _FM_ID_TO_NAME.items()},
        "schema_hash": SCHEMA_HASH,
        "order_hash": FEATURE_ORDER_HASH,
    }

def read_ontology() -> dict:
    """Per-feature ontology metadata: section, id, category, impl, states."""
    from features.registry import _ITERATED_SECTIONS
    doc = _load_yaml(REPO_ROOT / "configs" / "formulas" / "market_ontology.yaml")
    rows: dict = {}
    for section in _ITERATED_SECTIONS:
        for name, spec in (doc.get(section) or {}).items():
            if not isinstance(spec, dict):
                continue
            lin = spec.get("lineage") or {}
            vi = lin.get("vector_index")
            tax = spec.get("taxonomy") or {}
            impl = spec.get("impl")
            if isinstance(impl, dict):
                impl = impl.get("callable") or json.dumps(impl)
            rows[name] = {
                "section": section,
                "fm_id": spec.get("id"),
                "category": tax.get("category"),
                "knowledge_class": tax.get("knowledge_class"),
                "impl": impl or spec.get("produced_by"),
                "lifecycle": spec.get("lifecycle"),
                "vector_index": vi if isinstance(vi, int) else None,
                "has_states": bool(spec.get("states")),
                "is_vector_bound": isinstance(vi, int),
            }
    return {"iterated_sections": list(_ITERATED_SECTIONS), "entries": rows}


def read_states() -> dict:
    """State Ontology: vector-bound + non-vector stateful identities."""
    from features.feature_states import FeatureStateEncoder
    enc = FeatureStateEncoder()
    specs = {}
    for name in enc.stateful_features:
        sf = enc.spec(name)
        specs[name] = {
            "fm_id": sf.fm_id,
            "vector_index": sf.vector_index,
            "category": sf.category,
            "state_map": {str(k): v for k, v in sf.value_to_state.items()},
        }
    return {
        "vector_bound": list(enc.vector_bound_features),
        "all_stateful": list(enc.stateful_features),
        "continuous": list(enc.continuous_features),
        "specs": specs,
    }

def read_crt_identity() -> dict:
    """Decision Ontology: CRT state identities + constructor capabilities."""
    doc = _load_yaml(REPO_ROOT / "configs" / "formulas" / "crt_state_identity.yaml")
    ident = doc["identity"]
    states = {}
    for name, spec in (ident.get("states") or {}).items():
        states[name] = {
            "id": spec.get("id"),
            "subgraph": spec.get("subgraph"),
            "occupancy_class": spec.get("occupancy_class"),
            "timeframe_role": spec.get("timeframe_role"),
            "is_ground": spec.get("is_ground"),
            "requires_memory": spec.get("requires_memory"),
            "can_emit_bias": spec.get("can_emit_bias"),
            "can_emit_signal": spec.get("can_emit_signal"),
            "knowledge_status": spec.get("knowledge_status"),
            "lifecycle": spec.get("lifecycle"),
            "description": (spec.get("description") or "").strip(),
            "notes": (spec.get("notes") or "").strip(),
        }
    constructors = {}
    for cname, cspec in (ident.get("constructors") or {}).items():
        caps = cspec.get("capabilities") or {}
        gaps = []
        for g in (caps.get("blocking_gaps") or []):
            if isinstance(g, dict):
                gaps.append({"id": g.get("id"), "capability": g.get("capability"),
                             "summary": g.get("summary")})
            else:
                gaps.append({"id": None, "capability": None, "summary": str(g)})
        constructors[cname] = {
            "description": (cspec.get("description") or "").strip(),
            "capabilities": {
                "runtime_eligible": caps.get("runtime_eligible"),
                "reaches_signal_state": caps.get("reaches_signal_state"),
                "produces_trade_geometry": caps.get("produces_trade_geometry"),
                "produces_occupancy": caps.get("produces_occupancy"),
                "produces_memory": caps.get("produces_memory"),
                "covers_states": list(caps.get("covers_states") or []),
                "blocking_gaps": gaps,
            },
            "state_status": {k: {"reachable": v.get("reachable"),
                                 "defined": v.get("defined"),
                                 "unreachable_reason": v.get("unreachable_reason"),
                                 "construction_diverges_from_engine":
                                     v.get("construction_diverges_from_engine")}
                             for k, v in (cspec.get("states") or {}).items()},
        }
    return {
        "schema": ident.get("schema"),
        "version": ident.get("version"),
        "state_list": ident.get("state_list"),
        "parent_states": ident.get("parent_timeframe_states"),
        "valid_transitions": ident.get("valid_transitions"),
        "states": states,
        "constructors": constructors,
    }


def read_resolver_states() -> list:
    """Resolver predicates declared in market_crt_states.yaml (constructor-scope check)."""
    doc = _load_yaml(REPO_ROOT / "configs" / "formulas" / "market_crt_states.yaml")
    return [s.get("name") for s in (doc.get("states") or []) if isinstance(s, dict)]


def git_facts() -> dict:
    def _run(args):
        try:
            return subprocess.run(args, cwd=REPO_ROOT, capture_output=True, text=True,
                                  timeout=20).stdout.strip()
        except Exception:
            return ""
    return {"commit": _run(["git", "rev-parse", "HEAD"]) or "UNKNOWN",
            "branch": _run(["git", "rev-parse", "--abbrev-ref", "HEAD"]) or "UNKNOWN"}

