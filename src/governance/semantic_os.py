def required_checks_for_classes(classes: Iterable[str], path: Path = _CONTRACTS) -> list[str]:
    """Union of ``required_checks`` across the given change classes (L6 reuses this)."""
    data = _read_json(path) or {}
    contracts = data.get("change_classes") or {}
    out: set[str] = set()
    for name in classes:
        entry = contracts.get(name)
        if isinstance(entry, dict):
            out |= set(entry.get("required_checks") or [])
    return sorted(out)


def _prefixed_ids_from(paths: Iterable[Path], pattern: re.Pattern[str]) -> set[str]:
    out: set[str] = set()
    for p in paths:
        try:
            out |= set(pattern.findall(p.read_text(encoding="utf-8")))
        except Exception:  # noqa: BLE001
            continue
    return out


def foreign_id_namespace() -> dict[str, set[str]]:
    """Every id owned by another registry — CN/BD/JN must be disjoint from all of these.

    Sources are TRACKED files wherever possible so the check has full strength on a fresh clone.
    ``H-`` and framework ids fall back to a regex over their (tracked) seed scripts when the
    gitignored ``data/*.jsonl`` projection is absent.
    """
    mod_ids = {r.get("id") for r in _read_jsonl(_MODULE_STUBS) if r.get("id")}
    scr_ids = {r.get("id") for r in _read_jsonl(_SCRIPT_STUBS) if r.get("id")}

    hyp = {r.get("id") for r in _read_jsonl(_HYPOTHESIS_JSONL) if r.get("id")}
    if not hyp:
        hyp = _prefixed_ids_from([_HYPOTHESIS_SEED], re.compile(r"\bH-\d{3}\b"))

    fw = {r.get("id") for r in _read_jsonl(_FRAMEWORK_JSONL) if r.get("id")}
    if not fw:
        fw = _prefixed_ids_from(
            [_FRAMEWORK_SEED],
            re.compile(r"\b(?:KERNEL|DOMAIN|STYLE|STRATEGY|IMPL|INTENT|RISK|EXEC|COMP)-\d{3}\b"),
        )

    return {
        "ontology": ontology_ids(),
        "findings": valid_finding_ids(_FINDINGS_DOC),
        "module_attribution": {i for i in mod_ids if i},
        "script_registry": {i for i in scr_ids if i},
        "miar": miar_entry_ids(),
        "closure": closure_surface_ids(),
        "change_classes": change_class_names(),
        "hypotheses": {i for i in hyp if i},
        "framework": {i for i in fw if i},
    }


