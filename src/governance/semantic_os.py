"""SemanticOSRegistry — the hand-authored semantic layer (Concepts / Boundaries / Journeys).

The Semantic OS answers the questions code cannot: *why does this exist*, *what invariant must
never break*, *why this design*, *why was the alternative rejected*, *which finding justifies it*.
Everything code CAN answer — imports, consumers, package, ownership, size, tests, reachability —
is GENERATED by ``src/governance/semantic_objects.py`` and is a **schema violation** if hand-written
here (see ``_FORBIDDEN_HAND_FIELDS`` + ``validate_no_derived_in_source``).

Five hand-authored record kinds, one generated:

============  ==============  ==============================================================
Kind          Id              Role
============  ==============  ==============================================================
Concept       ``CN-``         Stable meaning. REFERENCES miar / closure / ontology / book /
                              findings by validated foreign key; owns none of them.
Boundary      ``BD-``         An architectural seam, **not a file list**. Owner + member GLOBS
                              + consumers + the invariant it protects. Survives churn.
Journey       ``JN-``         An ordered semantic path across concepts. Machine twin of
                              ``docs/architecture/signal-flow.md``.
Contract      ``CT-``         First-class constraints (inputs/outputs/guarantees/
                              non_guarantees/tests). May be referenced from BD.contract_ids.
FileIdentity  dotted slug     Rename-stable ``semantic_id -> semantic_name -> physical_path``
                              for one module, plus a ``filename_semantic_status`` classification
                              (ALIGNED/HISTORICAL/MISLEADING/COMPATIBILITY/SPLIT/UNKNOWN). Tier 1/2
                              curated in YAML; Tier 3 machine-derived at seed time (path_slug).
                              Grants no rename authority — advisory naming only.
Object        ``OBJ:``        100% generated — see ``semantic_objects.py``. Never authored.
============  ==============  ==============================================================

Authority (CLAUDE.md §6.5): every record pins ``authority = "advisory"``. Concept ownership and
boundary membership grant *navigability*, never *production authority* — only demonstrated G001
improvement does. ``validate_record`` rejects ``"production"`` outright.

Ontology precedence (§6.6): a Concept may CITE ``FM-*`` / ``SEM-*`` / ``UNK-*`` ids but may never
carry a formula. ``configs/formulas/market_ontology.yaml`` remains authority #1 for meaning.

Design notes (reuse, don't reinvent — CLAUDE.md §3.1):
  - class shape, ``ValidationError``, ``validate_record`` / ``dump`` mirror
    ``src/governance/framework_registry.py``;
  - evidence validation reuses that module's ``_resolve`` + ±30-line symbol-drift window;
  - finding validation reuses its ``valid_finding_ids()`` (``### F-NNN`` block regex).

Append-discipline (§6.2 rule 4): retired records stay in the YAML marked ``SUPERSEDED`` /
``RETIRED`` with ``superseded_by`` set. Never delete a record.

Usage:
    reg = SemanticOSRegistry.load()
    errors = reg.validate_all()
    concept = reg.get("CN-001")
"""
