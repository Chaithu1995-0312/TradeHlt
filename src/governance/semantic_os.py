    def validate_unique_ids_global(self) -> list[ValidationError]:
        """(2) CN/BD/JN/step ids unique among themselves AND disjoint from every other registry."""
        errors: list[ValidationError] = []
        seen: dict[str, str] = {}
        for record in self.records:
            rid = record.get("id")
            if not rid:
                continue
